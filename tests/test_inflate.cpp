EDEN_TEST(compressor_round_trips_varied_data) {
    std::vector<Bytes> samples;
    samples.push_back(Bytes());
    samples.push_back(Bytes{'a'});
    samples.push_back(Bytes(100000, 'z'));
    Bytes text;
    for (int i = 0; i < 2000; ++i) {
        const std::string line = "Out of Eden flows a river number " + std::to_string(i % 37) + " and it divides.\n";
        text.insert(text.end(), line.begin(), line.end());
    }
    samples.push_back(text);
    Bytes noise;
    std::uint32_t state = 12345;
    for (int i = 0; i < 70000; ++i) {
        state = state * 1664525u + 1013904223u;
        noise.push_back(static_cast<std::uint8_t>(state >> 24));
    }
    samples.push_back(noise);
    Bytes mixed = text;
    mixed.insert(mixed.end(), noise.begin(), noise.begin() + 5000);
    mixed.insert(mixed.end(), text.begin(), text.begin() + 3000);
    samples.push_back(mixed);
    for (const Bytes& sample : samples) {
        const Bytes packed = zlibWrapCompressed(sample.data(), sample.size());
        auto restored = inflateZlib(packed.data(), packed.size());
        EXPECT_TRUE(restored.ok());
        EXPECT_TRUE(restored.value() == sample);
    }
    const Bytes packedText = zlibWrapCompressed(text.data(), text.size());
    EXPECT_TRUE(packedText.size() * 8 < text.size());
}

EDEN_TEST(zip_writer_compresses_text_and_keeps_media_stored) {
    ZipWriter writer;
    writer.addText("big.txt", std::string(50000, 'x') + "tail");
    writer.add("pic.png", Bytes(500, 7));
    writer.addText("tiny.txt", "hi");
    const Bytes archive = writer.finish();
    EXPECT_TRUE(archive.size() < 2000);
    auto zip = ZipReader::open(archive);
    EXPECT_TRUE(zip.ok());
    EXPECT_EQ(zip.value().find("big.txt")->method, static_cast<std::uint16_t>(8));
    EXPECT_EQ(zip.value().find("pic.png")->method, static_cast<std::uint16_t>(0));
    EXPECT_EQ(zip.value().find("tiny.txt")->method, static_cast<std::uint16_t>(0));
    EXPECT_EQ(zip.value().readText("big.txt").value().size(), static_cast<std::size_t>(50004));
    EXPECT_EQ(zip.value().readText("tiny.txt").value(), std::string("hi"));
}
